// Helper to generate realistic starting candlestick bars
function generateInitialCandles(basePrice: number, volatility: number, count = 60, pipSize = 0.0001): Candle[] {
  const candles: Candle[] = [];
  let currentPrice = basePrice;
  const now = Date.now();
  const timeframeMs = 15 * 60 * 1000; // 15M candles

  for (let i = count; i >= 0; i--) {
    const time = now - i * timeframeMs;
    const delta = (Math.random() - 0.485) * volatility;
    const open = currentPrice;
    const close = Math.max(open + delta, pipSize * 10);
    const high = Math.max(open, close) + Math.random() * (volatility * 0.6);
    const low = Math.min(open, close) - Math.random() * (volatility * 0.6);
    const volume = Math.floor(Math.random() * 2500 + 400);

    candles.push({
      time,
      open: Number(open.toFixed(5)),
      high: Number(high.toFixed(5)),
      low: Number(low.toFixed(5)),
      close: Number(close.toFixed(5)),
      volume,
    });

    currentPrice = close;
  }
  return candles;
}

